<?php
require_once __DIR__.'/../app/Services/CentralPrintingSetup.php';
function setup_check($condition, $message) { if (!$condition) throw new RuntimeException($message); }
$directory = sys_get_temp_dir().'/print-setup-'.bin2hex(random_bytes(6));
mkdir($directory, 0700);
$path = $directory.'/existing.sqlite';
$db = new PDO('sqlite:'.$path);
$db->setAttribute(PDO::ATTR_ERRMODE, PDO::ERRMODE_EXCEPTION);
$db->exec('PRAGMA foreign_keys=ON');
$db->exec("CREATE TABLE erp_printers(id INTEGER PRIMARY KEY,name TEXT,network_uri TEXT,is_active INTEGER DEFAULT 1,updated_at TEXT); CREATE TABLE erp_work_centers(id INTEGER PRIMARY KEY,name TEXT,is_active INTEGER DEFAULT 1,default_printer_id INTEGER); INSERT INTO erp_printers(id,name,network_uri) VALUES(1,'Existente','ipp://printer/ipp/print'); INSERT INTO erp_work_centers(id,name,default_printer_id) VALUES(1,'Corte',1)");
$setup = new CentralPrintingSetup($db);
$status = $setup->status();
setup_check(!$status['installed'] && !$status['erp_ready'], 'Diagnóstico inicial não prepara nem ativa o sistema');
setup_check((int)$db->query("SELECT COUNT(*) FROM sqlite_master WHERE name GLOB 'erp_print_*'")->fetchColumn()===0, 'Diagnóstico não altera o esquema');
$status = $setup->prepare($directory.'/backup', 1);
setup_check($status['erp_ready'] && !$status['enabled'], 'ERP preparado sem ativar impressão');
setup_check($status['models_created']===3, 'Três modelos iniciais');
setup_check($status['agents']===0 && $status['printers']===0 && $status['associations']===0, 'Não inventar máquinas ou autorizações');
setup_check((int)$db->query('SELECT COUNT(*) FROM erp_print_jobs')->fetchColumn()===0, 'Preparação não cria trabalhos');
setup_check((int)$db->query('SELECT COUNT(*) FROM erp_printers')->fetchColumn()===1, 'Preservar impressoras existentes');
setup_check((int)$db->query('SELECT default_printer_id FROM erp_work_centers WHERE id=1')->fetchColumn()===1, 'Preservar associação legada');
setup_check(count(glob($directory.'/backup/printing-*.sql'))===1 && count(glob($directory.'/backup/catalog-*.sql'))===1, 'Snapshots antes de migração e catálogo');
$copy = new PDO('sqlite::memory:');
$copy->exec(file_get_contents(glob($directory.'/backup/catalog-*.sql')[0]));
setup_check((int)$copy->query('SELECT COUNT(*) FROM erp_print_templates')->fetchColumn()===0, 'Snapshot do catálogo restaurável antes dos seeds');
$again = $setup->prepare($directory.'/backup', 1);
setup_check($again['models_created']===0 && count(glob($directory.'/backup/*.sql'))===2, 'Preparação repetida idempotente');
$db->exec("UPDATE erp_print_templates SET code='custom_roll',name='Rolo personalizado' WHERE renderer='raw_material_roll_label'");
$again = $setup->prepare($directory.'/backup', 1);
setup_check($again['erp_ready'] && $again['models_created']===0, 'Reutilizar modelos personalizados equivalentes sem duplicar');
$db->exec("UPDATE erp_print_templates SET active=0 WHERE renderer='raw_material_roll_label'");
$again = $setup->prepare($directory.'/backup', 1);
setup_check(!$again['erp_ready'] && $again['models_created']===0, 'Preservar desativação deliberada e indicar pendência');
$db->exec("UPDATE erp_print_templates SET active=1 WHERE renderer='raw_material_roll_label'; UPDATE erp_print_config SET enabled=1 WHERE id=1");
$again = $setup->prepare($directory.'/backup', 1);
setup_check($again['enabled'], 'Atualização não desativa uma instalação já em uso');
// Name collisions must never overwrite a model configured by an administrator.
$db->exec("UPDATE erp_print_templates SET renderer='existing_pdf' WHERE code='finished_product_a4'");
$backupCount=count(glob($directory.'/backup/*.sql'));
$again = $setup->prepare($directory.'/backup', 1);
setup_check(count(glob($directory.'/backup/*.sql'))===$backupCount, 'Conflitos sem alterações não geram backups repetidos');
setup_check(!$again['erp_ready'] && $again['models_created']===0, 'Conflito de código fica visível sem substituir dados');
setup_check($db->query("SELECT renderer FROM erp_print_templates WHERE code='finished_product_a4'")->fetchColumn()==='existing_pdf', 'Modelo existente intacto');
$db = null;
foreach (glob($directory.'/backup/*') as $file) unlink($file);
unlink($directory.'/backup/.htaccess');
rmdir($directory.'/backup');
unlink($path);
rmdir($directory);
echo "Preparação ERP: catálogo, backup, idempotência, preservação e diagnóstico sem impressão validados.\n";
